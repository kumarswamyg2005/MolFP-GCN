"""Non-negotiable invariants, and where each one is enforced.

 1. Featurization is our own code (molfp/featurize.py), not PyG's MoleculeNet features.
    Every atom feature and bond rule is documented in a docstring table.
      -> featurize.py docstring; tests/test_featurize.py (dims, one-hots)
 2. Edges are undirected: every bond becomes two directed edges (i->j and j->i).
    Hydrogens are implicit (an atom feature), never explicit nodes.
      -> featurize.mol_to_data; test_benzene_graph, test_ethanol_graph
 3. Invalid SMILES never crash anything. The parser returns None + reason; the loader drops
    and logs the dropped row count; the demo shows a clear error message.
      -> featurize.parse_smiles, data.load_dataset, app validate(); test_invalid_smiles_*,
         test_app_rejects_*
 4. Split is Bemis-Murcko scaffold, 80/10/10, deterministic by seed; no scaffold in more than
    one split. Random split only as a labelled ablation.
      -> split.scaffold_split; test_scaffold_split_properties
 5. The test set is touched exactly once per final run; early stopping and hyperparameters
    use validation only.
      -> train.train never loads test indices; evaluate.run_gcn scores test once;
         test_train_never_sees_test
 6. ESOL target normalization uses train-split mean/std only; stats are saved in the
    checkpoint and inverted at inference.
      -> train.target_stats / make_loss / predict; test_normalization_*
 7. Tox21 missing labels are masked out of the loss and of per-task ROC-AUC, never filled with 0.
      -> train.masked_bce, metrics.masked_roc_auc; test_masked_bce_ignores_nan,
         test_masked_roc_auc_ignores_nan
 8. GCN and RF see the exact same split indices, saved to data/splits/{dataset}_seed{n}.json.
      -> split.get_split (hash-checked); evaluate asserts equal hashes;
         test_split_file_is_single_source_of_truth, test_gcn_and_rf_use_same_split
 9. Every reported number is mean ± std over seeds 0, 1, 2.
      -> SEEDS below; evaluate.summarize
10. The model is permutation-invariant: reordering atoms changes the prediction by < 1e-5.
      -> mean/max readout in model.py; test_permutation_invariance
11. Every figure and table in the report is generated by a script from saved results JSON.
      -> molfp/figures.py writes reports/figures/*.png and reports/tables.md
12. Demo input is capped at 200 characters and 100 heavy atoms; larger input is rejected with
    a message.
      -> MAX_SMILES_CHARS / MAX_HEAVY_ATOMS below, app validate(); test_app_rejects_*
"""

SEEDS = (0, 1, 2)
MAX_SMILES_CHARS = 200
MAX_HEAVY_ATOMS = 100
